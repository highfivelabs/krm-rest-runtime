"""Write a vendor's examples that show a kind with the kinds it needs.

  examples.py <vendor-repo>

A live test (hack/live/live.yaml) gives a kind that lives under another
resource the ID of one it makes first, with a setup call that saves it:

  before: [{method: POST, path: /projects, body: {...}, save: {project: id}}]
  kinds:  [{kind: ProjectWikiPage, spec: {projectID: "{{var:project}}", ...}}]

Where that call is the create of one of the vendor's own kinds (Project),
this writes examples/<Kind>/with-<Parent>.yaml: the parent as an object of
its kind, from its own live spec (or its sample), and the kind with
spec.fieldRefs taking the parent's value in place of the saved one. A parent
that needs a parent of its own gets it the same way. Live templates become
placeholders: {{cred:orgId}} is <orgId>, {{name}} the object's name.

Each example is tested by kindtest.ValidExampleFiles (go test ./...): every
object passes its CRD, and the controllers make them all, in order, on the
fake API and delete them again.

The repo's Upjet facts (hack/upjet/*.json, written by the factory's
`upjet sync`) give more such pairs: a reference from one of our kinds'
fields to a Terraform resource another of our kinds stands in for. Where
the field (case and underscores aside) is a string in the kind's sample
(fieldRefs fills a string, not a reference object or a list), its
extractor is Upjet's default (the target's ID, our status.id), and no
live-test example already shows the kind, this writes
examples/<Kind>/with-<Target>.yaml the same way: the target from its own
spec, and the kind with spec.fieldRefs taking the target's ID.

Not every such reference is our status.id (Upjet's default extractor is
the target's external name, which for some kinds is its name). One that
does not hold on the fake is listed, with why, in
hack/gen/examples-skip.yaml ({upjet: {<Kind>: <reason>}}); each skip is
printed, and a skip that matches nothing fails, so the list stays true.
"""
import glob
import json
import os
import re
import sys

import yaml

HEAD = "# Code generated by krm-rest-runtime/gen/examples.py from hack/live/live.yaml. DO NOT EDIT.\n"
UPJET_HEAD = "# Code generated by krm-rest-runtime/gen/examples.py from hack/upjet (Upjet references). DO NOT EDIT.\n"
VAR = re.compile(r"\{\{var:([A-Za-z0-9_.-]+)\}\}")
TEMPLATE = re.compile(r"\{\{([a-zA-Z_]+)(?::([A-Za-z0-9_.-]+))?\}\}")


def path_re(p):
    parts = re.split(r"(\{[^}]+\})", p.split("?")[0].rstrip("/"))
    return re.compile("^" + "".join("[^/]+" if x.startswith("{") else re.escape(x) for x in parts) + "/?$")


def fill(v, name):
    if isinstance(v, str):
        def sub(m):
            k, arg = m.group(1), m.group(2)
            if k in ("name", "run"):
                return name
            if k in ("name_", "run_"):
                return name.replace("-", "_")
            if k in ("NAME", "RUN"):
                return name.upper()
            if k in ("NAME_", "RUN_"):
                return name.replace("-", "_").upper()
            if k in ("cred", "env", "var"):
                return f"<{arg}>"
            if k == "date":
                return "2030-01-01"
            return m.group(0)
        return TEMPLATE.sub(sub, v)
    if isinstance(v, dict):
        return {k: fill(e, name) for k, e in v.items()}
    if isinstance(v, list):
        return [fill(e, name) for e in v]
    return v


class Vendor:
    def __init__(self, repo):
        self.repo = repo
        self.types = yaml.safe_load(open(os.path.join(repo, "types.yaml")))
        lp = os.path.join(repo, "hack", "live", "live.yaml")
        self.live = yaml.safe_load(open(lp)) if os.path.exists(lp) else {}
        # A draft is never reconciled: no example shows one.
        self.kinds = [k for k in self.types["kinds"] if k.get("readiness") != "draft"]
        self.upjet = []
        for f in sorted(glob.glob(os.path.join(repo, "hack", "upjet", "*.json"))):
            self.upjet.append(json.load(open(f)))

    def kind(self, name, group=None):
        return next((k for k in self.kinds if k["kind"] == name and (not group or k["group"] == group)), None)

    def live_kind(self, k):
        return next((lk for lk in self.live.get("kinds") or []
                     if lk.get("kind") == k["kind"] and lk.get("group", k["group"]) == k["group"] and not lk.get("skip")), None)

    def creator(self, call):
        """The kind whose create (or upsert) the setup call is."""
        path = TEMPLATE.sub("X", call["path"].split("?")[0])
        for k in self.kinds:
            op = k.get("create") or (k["read"] if k["shape"] == "upsert" else None)
            if op and op["method"].upper() == call["method"].upper() and path_re(op["path"]).match(path):
                return k
        return None

    def fake_has(self, parent, save):
        """Whether the fake API answers the saved field, so the example can
        be tested: the parent's ID, or a field the create sends back (the
        fake echoes the body). A nested field only the real API computes
        (Confluent's metadata.resource_name) is not."""
        env = parent.get("envelope") or ""
        p = save[len(env) + 1:] if env and save.startswith(env + "/") else save
        return (parent.get("id") or {}).get("from") == p or "/" not in p

    def field_path(self, parent, save, child, field):
        """Where the parent object holds the value the setup call saved."""
        env = parent.get("envelope") or ""
        p = save[len(env) + 1:] if env and save.startswith(env + "/") else save
        is_param = any(q["field"] == field for q in child.get("params") or [])
        if is_param and parent.get("id") and parent["id"]["from"] == p:
            return None  # status.id, the default
        return "status.atProvider." + p.replace("/", ".")

    def spec_of(self, k, name, calls):
        """k's spec as its live test (else its sample) gives it, and the
        parents its {{var:...}} fields take values from: [(parent, field,
        save)]."""
        lk = self.live_kind(k)
        if lk:
            spec = {} if lk.get("replaceSample") else dict(k.get("sample") or {})
            for f, v in (lk.get("spec") or {}).items():
                if v is None:
                    spec.pop(f, None)
                else:
                    spec[f] = v
            calls = (self.live.get("before") or []) + (lk.get("before") or [])
        else:
            spec = dict(k.get("sample") or {})
        refs = []
        for f, v in list(spec.items()):
            m = VAR.fullmatch(v) if isinstance(v, str) else None
            if not m:
                continue
            call = next((c for c in calls if m.group(1) in (c.get("save") or {})), None)
            parent = call and self.creator(call)
            save = call and call["save"][m.group(1)]
            if parent and self.fake_has(parent, save):
                refs.append((parent, f, save, call))
        return spec, refs, calls

    def objects(self, k, name, calls=(), depth=0, drop=()):
        """k as an object, after the objects it refers to. drop: fields left
        out (a parent of k's own kind, which would refer to itself)."""
        spec, refs, calls = self.spec_of(k, name, list(calls))
        for f in drop:
            spec.pop(f, None)
        refs = [r for r in refs if r[1] not in drop]
        out = []
        field_refs = {}
        for parent, f, save, call in refs:
            own = parent["kind"] == k["kind"]  # a subgroup's parent group
            pname = name + "-parent" if own else "example-" + parent["kind"].lower()
            if depth < 3:
                sub = self.objects(parent, pname, calls, depth + 1, drop=(f,) if own else ())
                out += [o for o in sub if o not in out]
            ref = {"kind": parent["kind"], "name": pname}
            if sum(1 for x in self.kinds if x["kind"] == parent["kind"]) > 1:
                ref = {"apiVersion": f"{parent['group']}/{parent['version']}", **ref}
            fp = self.field_path(parent, save, k, f)
            if fp:
                ref["fieldPath"] = fp
            field_refs[f] = ref
            spec.pop(f, None)
        spec = fill(spec, name)
        if field_refs:
            spec["fieldRefs"] = field_refs
        out.append({"apiVersion": f"{k['group']}/{k['version']}", "kind": k["kind"],
                    "metadata": {"name": name, "namespace": "default"}, "spec": spec})
        return out


def norm(s):
    return re.sub(r"[^a-z0-9]", "", s.lower())


def upjet_refs(v):
    """{(group, kind): [(field, target kind)]} from the Upjet facts: each
    reference whose target one of our kinds serves, on a field the kind's
    sample sets, taking the target's ID (Upjet's default extractor)."""
    out = {}
    for sl in v.upjet:
        for e in sl.get("entries") or []:
            o = e.get("ours") or {}
            k = v.kind(o.get("kind", ""), o.get("group"))
            if not k:
                continue
            sample = {norm(f): f for f in (k.get("sample") or {})}
            for r in e["facts"].get("references") or []:
                if r.get("extractor") or "." in r["field"]:
                    continue  # not the target's ID, or a nested field
                f = sample.get(norm(r["field"]))
                # fieldRefs fills a top-level field with the target's ID: a
                # string. A reference object ({id, type}) or a list of IDs
                # is out of its reach.
                if not f or not isinstance(k["sample"][f], str):
                    continue
                for served in (e.get("targetsOurs") or {}).get(r.get("target", "")) or []:
                    g, _, tk = served.partition("/")
                    t = v.kind(tk, g)
                    if t and t is not k and (f, t) not in out.setdefault((k["group"], k["kind"]), []):
                        out[(k["group"], k["kind"])].append((f, t))
    return out


def upjet_objects(v, k, refs):
    """k after the targets of its Upjet references, each from its own spec."""
    name = "example-" + k["kind"].lower()
    out, field_refs = [], {}
    spec, _, _ = v.spec_of(k, name, [])
    for f, t in refs:
        if f in field_refs:
            continue  # one target per field
        tname = "example-" + t["kind"].lower()
        for o in v.objects(t, tname):
            if o not in out:
                out.append(o)
        ref = {"kind": t["kind"], "name": tname}
        if sum(1 for x in v.kinds if x["kind"] == t["kind"]) > 1:
            ref = {"apiVersion": f"{t['group']}/{t['version']}", **ref}
        field_refs[f] = ref
        spec.pop(f, None)
    spec = fill(spec, name)
    spec["fieldRefs"] = field_refs
    out.append({"apiVersion": f"{k['group']}/{k['version']}", "kind": k["kind"],
                "metadata": {"name": name, "namespace": "default"}, "spec": spec})
    return out


def write(out_dir, k, objs, head):
    parents = "-and-".join(dict.fromkeys(o["kind"] for o in objs[:-1]))  # each kind once
    d = os.path.join(out_dir, k["kind"])
    os.makedirs(d, exist_ok=True)
    docs = [yaml.safe_dump(o, sort_keys=False, default_flow_style=False, width=200) for o in objs]
    with open(os.path.join(d, f"with-{parents}.yaml"), "w") as f:
        f.write(head + "---\n".join(docs))


def main():
    repo = sys.argv[1]
    v = Vendor(repo)
    out_dir = os.path.join(repo, "examples")
    for old in glob.glob(os.path.join(out_dir, "*", "with-*.yaml")):
        text = open(old).read()
        if text.startswith(HEAD) or text.startswith(UPJET_HEAD):
            os.remove(old)
    n = 0
    shown = set()
    for k in v.kinds:
        if not v.live_kind(k):
            continue
        objs = v.objects(k, "example-" + k["kind"].lower())
        if len(objs) < 2:
            continue
        write(out_dir, k, objs, HEAD)
        shown.add((k["group"], k["kind"]))
        n += 1
    nu = 0
    sp = os.path.join(repo, "hack", "gen", "examples-skip.yaml")
    skip = ((yaml.safe_load(open(sp)) or {}).get("upjet") or {}) if os.path.exists(sp) else {}
    used = set()
    for (g, kn), refs in sorted(upjet_refs(v).items()):
        if (g, kn) in shown:
            continue
        if kn in skip:
            used.add(kn)
            print(f"{kn}: no example from Upjet references ({skip[kn]})", file=sys.stderr)
            continue
        write(out_dir, v.kind(kn, g), upjet_objects(v, v.kind(kn, g), refs), UPJET_HEAD)
        nu += 1
    for d in glob.glob(os.path.join(out_dir, "*")):
        if os.path.isdir(d) and not os.listdir(d):
            os.rmdir(d)
    print(f"{v.types['vendor']}: {n} examples with the kinds they need from live tests, {nu} from Upjet references", file=sys.stderr)
    if set(skip) - used:
        sys.exit(f"hack/gen/examples-skip.yaml: no Upjet example to skip for {', '.join(sorted(set(skip) - used))}")


if __name__ == "__main__":
    main()
